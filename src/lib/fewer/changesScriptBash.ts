/**
 * The bash program that replays graph edits onto a folder on disk.
 *
 * Kept apart from the diff logic so the shell stays readable: this file is
 * the *program*, `changesScript.ts` is the *plan* that fills it in.
 *
 * Every bash parameter expansion is written `\${…}` so the TypeScript
 * template literal hands bash the literal text — the generated script is
 * syntax-checked by `bash -n` in the test suite, so a mistake here fails
 * loudly instead of at the user's terminal.
 */

/** Header, argument parsing, the folder check and the interactive prompts. */
export const BASH_PREAMBLE = `#!/usr/bin/env bash
# Generated by fewer — replay the edits you made in the graph onto a folder on disk.
# __SUMMARY__
# Baseline: __BASELINE__ entries imported from "__ROOT__" on __DATE__
#
# Usage:
#   bash __FILE__ [folder]
#   --dry-run       print the commands, change nothing
#   --allow-delete  allow the deletions listed below
#   --yes           don't ask for confirmation
#   --force         skip the folder checks
set -euo pipefail
[ -n "\${BASH_VERSION:-}" ] || exec bash "$0" "$@"

ROOT_NAME='__ROOT__'
CHANGES=__CHANGES__
DELETES=__DELETES__

target='.'
DRY_RUN=0
ALLOW_DELETE=0
ASSUME_YES=0
FORCE=0

die() { printf '\\n✗ %s\\n' "$*" >&2; exit 1; }
say() { printf '%s\\n' "$*"; }
run() { if [ "$DRY_RUN" = 1 ]; then printf '+ %s\\n' "$*"; else "$@"; fi; }

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run)      DRY_RUN=1 ;;
    --allow-delete) ALLOW_DELETE=1 ;;
    --yes|-y)       ASSUME_YES=1 ;;
    --force)        FORCE=1 ;;
    -h|--help)      sed -n '2,14p' "$0"; exit 0 ;;
    *)              target="$1" ;;
  esac
  shift
done

cd "$target" || die "cannot enter folder '$target'"

# ── 1. the folder must be the one that was imported ────────────────────────
if [ "$FORCE" = 0 ]; then
  here="$(basename "$(pwd)")"
  [ "$here" = "$ROOT_NAME" ] || die "wrong folder: expected '$ROOT_NAME', got '$here' (--force to override)"
fi

# ── 2. what should we do? ─────────────────────────────────────────────────
if [ "$ASSUME_YES" = 0 ] && [ -t 0 ]; then
  say ""
  say "fewer — $CHANGES change(s) for \\"$ROOT_NAME\\" in $(pwd)"
  printf 'Apply them? [y]es / [d]ry-run / [n]o (default: n): '
  read -r reply || reply=''
  case "\${reply:-n}" in
    y|Y|yes) ;;
    d|D|dry) DRY_RUN=1 ;;
    *) say "Nothing changed."; exit 0 ;;
  esac
  if [ "$DELETES" -gt 0 ] && [ "$ALLOW_DELETE" = 0 ]; then
    printf 'Also delete %s item(s)? This cannot be undone. [y/N]: ' "$DELETES"
    read -r reply || reply=''
    case "$reply" in y|Y|yes) ALLOW_DELETE=1 ;; esac
  fi
elif [ "$DELETES" -gt 0 ] && [ "$ALLOW_DELETE" = 0 ]; then
  say "note: no terminal to confirm — $DELETES deletion(s) will be skipped"
fi

`;
/** The plan arrays plus the helpers and the pre-flight checks. */
export const BASH_CHECKS = `# ── 3. the plan ──────────────────────────────────────────────────────────
__PLAN__

is_move_source() {
  local i=0
  while [ "$i" -lt "$((N_MOVES * 2))" ]; do
    [ "\${MOVES[$i]}" = "$1" ] && return 0
    i=$((i+2))
  done
  return 1
}

is_delete_path() {
  local i=0
  while [ "$i" -lt "$N_DELETES" ]; do
    [ "\${DELETE_PATHS[$i]}" = "$1" ] && return 0
    i=$((i+1))
  done
  return 1
}

# ── 4. checks (nothing has been touched yet) ──────────────────────────────
if [ "$FORCE" = 0 ]; then
  i=0
  while [ "$i" -lt "$((N_MOVES * 2))" ]; do
    from="\${MOVES[$i]}"
    [ -e "$from" ] || die "missing '$from' — this does not look like the imported folder (--force to override)"
    i=$((i+2))
  done
  i=0
  while [ "$i" -lt "$((N_MOVES * 2))" ]; do
    from="\${MOVES[$i]}"; to="\${MOVES[$((i+1))]}"
    if [ -e "$to" ] && [ "$to" != "$from" ] && ! is_move_source "$to" && ! is_delete_path "$to"; then
      die "'$to' already exists and is neither moved nor deleted — resolve it by hand (--force to override)"
    fi
    i=$((i+2))
  done
  present=0
  i=0
  while [ "$i" -lt "$N_FINGERPRINT" ]; do
    [ -e "\${FINGERPRINT[$i]}" ] && present=$((present+1))
    i=$((i+1))
  done
  if [ "$present" -lt "$FINGERPRINT_MIN" ]; then
    die "only $present of $N_FINGERPRINT sampled paths from the import are here — wrong folder? (--force to override)"
  fi
fi

`;
/** Applies the plan: stage every source, commit every destination, then the rest. */
export const BASH_APPLY = `# ── 5. apply ───────────────────────────────────────────────────────────
staging=''
done_ok=0
cleanup() {
  if [ "$done_ok" = 1 ]; then
    if [ -n "$staging" ]; then rm -rf "$staging"; fi
  else
    if [ -n "$staging" ]; then printf '\\n✗ stopped — the moved files are still in %s\\n' "$staging" >&2; fi
  fi
}
trap cleanup EXIT

if [ "$N_MOVES" -gt 0 ]; then
  if [ "$DRY_RUN" = 1 ]; then
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      idx="\${COMMIT_ORDER[$j]}"
      printf '+ mv %q %q\\n' "\${MOVES[$((idx*2))]}" "\${MOVES[$((idx*2+1))]}"
      j=$((j+1))
    done
  else
    # Every source is moved aside first, so a swap (A→B, B→A) and any other
    # cycle just works — the destinations are free by the time we commit.
    staging="$(mktemp -d .fewer-staging.XXXXXX)"
    i=0
    while [ "$i" -lt "$((N_MOVES * 2))" ]; do
      from="\${MOVES[$i]}"
      say "· move aside $from"
      mv -- "$from" "$staging/$((i/2))"
      i=$((i+2))
    done
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      idx="\${COMMIT_ORDER[$j]}"
      to="\${MOVES[$((idx*2+1))]}"
      parent="$(dirname -- "$to")"
      if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
      say "· move to $to"
      mv -- "$staging/$idx" "$to"
      j=$((j+1))
    done
  fi
fi

i=0
while [ "$i" -lt "$N_PRE_DELETES" ]; do
  p="\${PRE_DELETES[$i]}"
  say "· delete $p"
  if [ -e "$p" ]; then rm -rf -- "$p"; fi
  i=$((i+1))
done

i=0
while [ "$i" -lt "$N_MKDIRS" ]; do
  d="\${MKDIRS[$i]}"
  say "· folder $d"
  run mkdir -p -- "$d"
  i=$((i+1))
done

i=0
while [ "$i" -lt "$((N_COPIES * 2))" ]; do
  src="\${COPIES[$i]}"; dst="\${COPIES[$((i+1))]}"
  parent="$(dirname -- "$dst")"
  if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
  say "· copy $src → $dst"
  run cp -R -- "$src" "$dst"
  i=$((i+2))
done

i=0
while [ "$i" -lt "$N_TOUCHES" ]; do
  f="\${TOUCHES[$i]}"
  parent="$(dirname -- "$f")"
  if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
  say "· file $f"
  run touch -- "$f"
  i=$((i+1))
done

i=0
while [ "$i" -lt "$((N_LINKS * 2))" ]; do
  l="\${LINKS[$i]}"; t="\${LINKS[$((i+1))]}"
  parent="$(dirname -- "$l")"
  if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
  say "· link $l → $t"
  run ln -sfn -- "$t" "$l"
  i=$((i+2))
done

if [ "$N_DELETES" -gt 0 ]; then
  if [ "$ALLOW_DELETE" = 1 ]; then
    i=0
    while [ "$i" -lt "$N_DELETES" ]; do
      p="\${DELETE_PATHS[$i]}"
      say "· delete $p"
      if [ -e "$p" ]; then rm -rf -- "$p"; fi
      i=$((i+1))
    done
  else
    i=0
    while [ "$i" -lt "$N_DELETES" ]; do
      printf '· skipped delete %q (not allowed)\\n' "\${DELETE_PATHS[$i]}"
      i=$((i+1))
    done
  fi
fi

done_ok=1
say ""
say "Done — $CHANGES change(s) applied to $(pwd)."
`;

/**
 * The bash program that replays graph edits onto a folder on disk.
 *
 * Kept apart from the diff logic so the shell stays readable: this file is
 * the *program*, `changesScript.ts` is the *plan* that fills it in.
 *
 * Every bash parameter expansion is written `\${…}` so the TypeScript
 * template literal hands bash the literal text — the generated script is
 * syntax-checked by `bash -n` in the test suite, so a mistake here fails
 * loudly instead of at the user's terminal.
 */

/** Header, argument parsing, the folder check and the interactive prompts. */
export const BASH_PREAMBLE = `#!/usr/bin/env bash
# Generated by fewer — replay the edits you made in the graph onto a folder on disk.
# __SUMMARY__
# Baseline: __BASELINE__ entries imported from "__ROOT__" on __DATE__
__NOTES__
#
# Usage:
#   bash __FILE__ [folder]
#   --dry-run       print the commands, change nothing
#   --allow-delete  allow the deletions listed below
#   --yes           don't ask for confirmation
#   --force         skip the folder checks
set -euo pipefail
[ -n "\${BASH_VERSION:-}" ] || exec bash "$0" "$@"

ROOT_NAME='__ROOT__'
ROOT_EXTRACT_FROM='__ROOT_EXTRACT_FROM__'
ROOT_EXTRACT_TO='__ROOT_EXTRACT_TO__'
CHANGES=__CHANGES__
DELETES=__DELETES__
NOTES_COUNT=__NOTES_COUNT__

target='.'
DRY_RUN=0
ALLOW_DELETE=0
ASSUME_YES=0
FORCE=0
KEEP_ARCHIVE=0

die() { printf '\\n✗ %s\\n' "$*" >&2; exit 1; }
say() { printf '%s\\n' "$*"; }
run() { if [ "$DRY_RUN" = 1 ]; then printf '+ %s\\n' "$*"; else "$@"; fi; }

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run)      DRY_RUN=1 ;;
    --allow-delete) ALLOW_DELETE=1 ;;
    --yes|-y)       ASSUME_YES=1 ;;
    --force)        FORCE=1 ;;
    --keep-archive) KEEP_ARCHIVE=1 ;;
    -h|--help)      sed -n '2,14p' "$0"; exit 0 ;;
    *)              target="$1" ;;
  esac
  shift
done

# ── 0. is there anything to replay at all? ────────────────────────────────
if [ "$CHANGES" -eq 0 ]; then
  if [ "$NOTES_COUNT" -gt 0 ]; then
    say "Nothing to replay in \\"$ROOT_NAME\\" — the changes you made are inside an archive, and an archive is one file."
    say "Open the archive itself and export the changes from there."
  else
    say "Nothing to change in \\"$ROOT_NAME\\"."
  fi
  exit 0
fi

cd "$target" || die "cannot enter folder '$target'"

# ── 1. the folder must be the one that was imported ────────────────────────
# A root extraction runs in the archive's PARENT: the folder does not exist
# yet, so there is no name to check — the archive file is checked instead.
if [ "$FORCE" = 0 ] && [ -z "$ROOT_EXTRACT_FROM" ]; then
  here="$(basename "$(pwd)")"
  [ "$here" = "$ROOT_NAME" ] || die "wrong folder: expected '$ROOT_NAME', got '$here' (--force to override)"
fi

# ── 2. what should we do? ─────────────────────────────────────────────────
if [ "$ASSUME_YES" = 0 ] && [ -t 0 ]; then
  say ""
  say "fewer — $CHANGES change(s) for \\"$ROOT_NAME\\" in $(pwd)"
  printf 'Apply them? [y]es / [d]ry-run / [n]o (default: n): '
  read -r reply || reply=''
  case "\${reply:-n}" in
    y|Y|yes) ;;
    d|D|dry) DRY_RUN=1 ;;
    *) say "Nothing changed."; exit 0 ;;
  esac
  if [ "$DELETES" -gt 0 ] && [ "$ALLOW_DELETE" = 0 ]; then
    printf 'Also delete %s item(s)? This cannot be undone. [y/N]: ' "$DELETES"
    read -r reply || reply=''
    case "$reply" in y|Y|yes) ALLOW_DELETE=1 ;; esac
  fi
elif [ "$DELETES" -gt 0 ] && [ "$ALLOW_DELETE" = 0 ]; then
  say "note: no terminal to confirm — $DELETES deletion(s) will be skipped"
fi

`;
/** The plan arrays plus the helpers and the pre-flight checks. */
export const BASH_CHECKS = `# ── 3. the plan ──────────────────────────────────────────────────────────
__PLAN__

# ── the archives in this folder ───────────────────────────────────────────
# An archive is a real file: the edits you made inside it are applied to the
# archive itself, with 7-Zip (or Python). Each archive gets its own plan file.
ARCHIVE_COUNT=__ARCHIVE_COUNT__
ARCHIVE_PLANS=''
__ARCHIVE_PLANS__

is_move_source() {
  local i=0
  while [ "$i" -lt "$((N_MOVES * 2))" ]; do
    [ "\${MOVES[$i]}" = "$1" ] && return 0
    i=$((i+2))
  done
  return 1
}

is_delete_path() {
  local i=0
  while [ "$i" -lt "$N_DELETES" ]; do
    [ "\${DELETE_PATHS[$i]}" = "$1" ] && return 0
    i=$((i+1))
  done
  return 1
}

# ── 4. checks (nothing has been touched yet) ──────────────────────────────
if [ "$FORCE" = 0 ]; then
  i=0
  while [ "$i" -lt "$((N_MOVES * 2))" ]; do
    from="\${MOVES[$i]}"
    [ -e "$from" ] || die "missing '$from' — this does not look like the imported folder (--force to override)"
    i=$((i+2))
  done
  i=0
  while [ "$i" -lt "$((N_MOVES * 2))" ]; do
    from="\${MOVES[$i]}"; to="\${MOVES[$((i+1))]}"
    if [ -e "$to" ] && [ "$to" != "$from" ] && ! is_move_source "$to" && ! is_delete_path "$to"; then
      die "'$to' already exists and is neither moved nor deleted — resolve it by hand (--force to override)"
    fi
    i=$((i+2))
  done
  present=0
  i=0
  while [ "$i" -lt "$N_FINGERPRINT" ]; do
    [ -e "\${FINGERPRINT[$i]}" ] && present=$((present+1))
    i=$((i+1))
  done
  if [ "$present" -lt "$FINGERPRINT_MIN" ]; then
    die "only $present of $N_FINGERPRINT sampled paths from the import are here — wrong folder? (--force to override)"
  fi
fi

`;
/** Applies the plan: stage every source, commit every destination, then the rest. */
export const BASH_APPLY = `# ── 5. apply ───────────────────────────────────────────────────────────
staging=''
done_ok=0
cleanup() {
  if [ "$done_ok" = 1 ]; then
    if [ -n "$staging" ]; then rm -rf "$staging"; fi
  else
    if [ -n "$staging" ]; then printf '\\n✗ stopped — the moved files are still in %s\\n' "$staging" >&2; fi
  fi
  if [ "\${TRANSITION_WORK_OWN:-0}" = 1 ] && [ -n "\${ARCHIVE_WORK:-}" ]; then rm -rf "$ARCHIVE_WORK"; fi
}
trap cleanup EXIT

# ── 4. transitions: cards that changed shape ──────────────────────────────
# A folder compressed into an archive is packed from its own CONTENTS (the
# archive holds what the graph shows under the card); an archive extracted
# into a folder is unpacked into it. Both build the new side beside the old
# one and move it into place, so a failure leaves the original untouched.
if [ "$N_EXTRACTS" -gt 0 ] || [ "$N_COMPRESSES" -gt 0 ]; then
  if ! { command -v zip >/dev/null 2>&1 && command -v unzip >/dev/null 2>&1; }; then
    ARCHIVE_WORK="\${ARCHIVE_WORK:-$(mktemp -d)}"
    TRANSITION_WORK_OWN=1
    archive_engine
  fi

  extract_archive() {
    local archive="$1" dest="$2"
    case "$archive" in
      *.zip|*.ZIP)
        if command -v unzip >/dev/null 2>&1; then unzip -q "$archive" -d "$dest"; return $?; fi
        ;;
    esac
    if [ -n "$SEVENZIP" ]; then
      "$SEVENZIP" x -bso0 -bsp0 -o"$dest" "$archive"
      return $?
    fi
    case "$archive" in
      *.zip|*.ZIP)
        if [ -n "$PYTHON" ]; then
          "$PYTHON" "$ARCHIVE_WORK/fewer_zip.py" --unpack "$archive" "$dest"
          return $?
        fi
        ;;
    esac
    say "cannot extract '$archive': install unzip or 7-Zip"
    return 1
  }

  unpack_archive() {
    local archive="$1" dest="$2" tmp="\${2}.fewer-tmp" only
    rm -rf -- "$tmp"
    mkdir -p -- "$tmp"
    extract_archive "$archive" "$tmp" || return 1
    # A .tar.gz / .tar.xz is two layers: the first pass hands back the .tar.
    only="$(ls -A "$tmp" 2>/dev/null)"
    case "$only" in
      *.tar)
        mv -- "$tmp/$only" "$tmp/.fewer-inner.tar"
        rm -rf -- "$tmp/$only"
        extract_archive "$tmp/.fewer-inner.tar" "$tmp" || return 1
        rm -f -- "$tmp/.fewer-inner.tar"
        ;;
    esac
    rm -rf -- "$dest"
    mv -- "$tmp" "$dest"
  }

  pack_folder() {
    local folder="$1" archive="$2" temp="\${2%.zip}.fewer-new.zip" abs
    abs="$(cd "$(dirname -- "$archive")" && pwd)/$(basename -- "$temp")"
    rm -f -- "$temp"
    if command -v zip >/dev/null 2>&1; then
      ( cd "$folder" && zip -q -r "$abs" . ) || return 1
    elif [ -n "$SEVENZIP" ]; then
      ( cd "$folder" && "$SEVENZIP" a -bso0 -bsp0 "$abs" . ) || return 1
    elif [ -n "$PYTHON" ]; then
      "$PYTHON" "$ARCHIVE_WORK/fewer_zip.py" --pack "$folder" "$temp" || return 1
    else
      say "cannot create '$archive': install zip, 7-Zip or Python 3"
      return 1
    fi
    mv -f -- "$temp" "$archive"
  }

  if [ -n "$ROOT_EXTRACT_FROM" ]; then
    say "· extract $ROOT_EXTRACT_FROM → $ROOT_EXTRACT_TO"
    if [ "$DRY_RUN" = 1 ]; then
      printf '+ unpack %q into %q\\n' "$ROOT_EXTRACT_FROM" "$ROOT_EXTRACT_TO"
    else
      [ -f "$ROOT_EXTRACT_FROM" ] || die "cannot find '$ROOT_EXTRACT_FROM' here — run the script in its folder"
      unpack_archive "$ROOT_EXTRACT_FROM" "$ROOT_EXTRACT_TO" ||
        die "could not extract '$ROOT_EXTRACT_FROM' — nothing changed"
      if [ "$KEEP_ARCHIVE" = 0 ]; then rm -f -- "$ROOT_EXTRACT_FROM"; fi
      cd "$ROOT_EXTRACT_TO" || die "cannot enter '$ROOT_EXTRACT_TO'"
    fi
  fi

  i=0
  while [ "$i" -lt "$N_EXTRACTS" ]; do
    from="\${EXTRACT_FROM[$i]}"; to="\${EXTRACT_TO[$i]}"
    say "· extract $from → $to"
    if [ "$DRY_RUN" = 1 ]; then
      printf '+ unpack %q into %q\\n' "$from" "$to"
    else
      unpack_archive "$from" "$to" || die "could not extract '$from' — nothing changed"
      if [ "$KEEP_ARCHIVE" = 0 ]; then rm -f -- "$from"; fi
    fi
    i=$((i+1))
  done

  i=0
  while [ "$i" -lt "$N_COMPRESSES" ]; do
    from="\${COMPRESS_FROM[$i]}"; to="\${COMPRESS_TO[$i]}"
    say "· compress $from → $to"
    if [ "$DRY_RUN" = 1 ]; then
      printf '+ compress %q into %q\\n' "$from" "$to"
    else
      pack_folder "$from" "$to" || die "could not compress '$from' — it is unchanged"
      rm -rf -- "$from"
    fi
    i=$((i+1))
  done
fi

# A deletion that frees the path another entry moves into has to happen first,
# or that move would land inside the folder that is still there.
i=0
while [ "$i" -lt "$N_PRE_DELETES" ]; do
  p="\${PRE_DELETES[$i]}"
  say "· delete $p"
  if [ -e "$p" ]; then rm -rf -- "$p"; fi
  i=$((i+1))
done

if [ "$N_MOVES" -gt 0 ]; then
  if [ "$DRY_RUN" = 1 ]; then
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      idx="\${COMMIT_ORDER[$j]}"
      printf '+ mv %q %q\\n' "\${MOVES[$((idx*2))]}" "\${MOVES[$((idx*2+1))]}"
      j=$((j+1))
    done
  else
    # Every source is moved aside first, so a swap (A→B, B→A) and any other
    # cycle just works — the destinations are free by the time we commit.
    staging="$(mktemp -d .fewer-staging.XXXXXX)"
    i=0
    while [ "$i" -lt "$((N_MOVES * 2))" ]; do
      from="\${MOVES[$i]}"
      say "· move aside $from"
      mv -- "$from" "$staging/$((i/2))"
      i=$((i+2))
    done
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      idx="\${COMMIT_ORDER[$j]}"
      to="\${MOVES[$((idx*2+1))]}"
      parent="$(dirname -- "$to")"
      if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
      say "· move to $to"
      mv -- "$staging/$idx" "$to"
      j=$((j+1))
    done
  fi
fi

i=0
while [ "$i" -lt "$N_MKDIRS" ]; do
  d="\${MKDIRS[$i]}"
  say "· folder $d"
  run mkdir -p -- "$d"
  i=$((i+1))
done

i=0
while [ "$i" -lt "$((N_COPIES * 2))" ]; do
  src="\${COPIES[$i]}"; dst="\${COPIES[$((i+1))]}"
  parent="$(dirname -- "$dst")"
  if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
  say "· copy $src → $dst"
  run cp -R -- "$src" "$dst"
  i=$((i+2))
done

i=0
while [ "$i" -lt "$N_TOUCHES" ]; do
  f="\${TOUCHES[$i]}"
  parent="$(dirname -- "$f")"
  if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
  say "· file $f"
  run touch -- "$f"
  i=$((i+1))
done

i=0
while [ "$i" -lt "$((N_LINKS * 2))" ]; do
  l="\${LINKS[$i]}"; t="\${LINKS[$((i+1))]}"
  parent="$(dirname -- "$l")"
  if [ "$parent" != "." ] && [ ! -d "$parent" ]; then mkdir -p -- "$parent"; fi
  say "· link $l → $t"
  run ln -sfn -- "$t" "$l"
  i=$((i+2))
done

if [ "$N_DELETES" -gt 0 ]; then
  if [ "$ALLOW_DELETE" = 1 ]; then
    i=0
    while [ "$i" -lt "$N_DELETES" ]; do
      p="\${DELETE_PATHS[$i]}"
      say "· delete $p"
      if [ -e "$p" ]; then rm -rf -- "$p"; fi
      i=$((i+1))
    done
  else
    i=0
    while [ "$i" -lt "$N_DELETES" ]; do
      printf '· skipped delete %q (not allowed)\\n' "\${DELETE_PATHS[$i]}"
      i=$((i+1))
    done
  fi
fi

done_ok=1
say ""
say "Done — $CHANGES change(s) applied to $(pwd)."
`;

/**
 * The folder script's archive section: one plan file per archive, and the
 * call that applies them with 7-Zip (or Python).
 */
export const BASH_ARCHIVE_SECTION = `
# ── 6. the archives ───────────────────────────────────────────────────────
# An archive is a real file in this folder: the edits you made inside it are
# applied to the archive itself, in place.
if [ "$ARCHIVE_COUNT" -gt 0 ]; then
  ARCHIVE_WORK_OWN=0
  if [ -z "\${ARCHIVE_WORK:-}" ]; then ARCHIVE_WORK="$(mktemp -d)"; ARCHIVE_WORK_OWN=1; fi
  j=0
  while [ "$j" -lt "$ARCHIVE_COUNT" ]; do
    archive="\${ARCHIVE_NAMES[$j]}"
    plan="$ARCHIVE_WORK/plan-$j.tsv"
    printf '%s\\n' "\${ARCHIVE_ROWS[$j]}" > "$plan"
    say "· editing $archive"
    apply_archive_plan "$archive" "$plan"
    j=$((j+1))
  done
  if [ "$ARCHIVE_WORK_OWN" = 1 ]; then rm -rf "$ARCHIVE_WORK"; fi
fi
`;

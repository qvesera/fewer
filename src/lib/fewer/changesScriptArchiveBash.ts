/**
 * The bash program that replays graph edits INSIDE an archive.
 *
 * The archive is one file (`backup.zip`), so the target is a file rather than
 * a folder, and every operation goes through an archive engine:
 *
 *   7z rn arc.zip old new ...   rename / move
 *   7z d  arc.zip path ...      delete
 *   7z a  arc.zip staged ...    add
 *
 * …or, when 7-Zip is not installed, the Python fallback, which rebuilds the
 * archive with the standard library.
 *
 * `7z rn` renames one pair at a time, so the moves go through the same
 * two-phase staging as the folder script: every source is renamed aside to a
 * temporary name first, then each temporary name is renamed to its real
 * destination. That is what makes a swap (A→B, B→A) and a chain (A→B, B→C)
 * work.
 */
export const BASH_ARCHIVE_PREAMBLE = `#!/usr/bin/env bash
# Generated by fewer — replay the edits you made in the graph inside an archive.
# __SUMMARY__
# Archive: "__ROOT__" on __DATE__
__NOTES__
#
# Usage:
#   bash __FILE__ [archive.zip]
#   --dry-run       print the commands, change nothing
#   --allow-delete  allow the deletions listed below
#   --yes           don't ask for confirmation
#   --force         skip the checks
set -euo pipefail
[ -n "\${BASH_VERSION:-}" ] || exec bash "$0" "$@"

ARCHIVE_NAME='__ROOT__'
CHANGES=__CHANGES__
DELETES=__DELETES__

target='.'
DRY_RUN=0
ALLOW_DELETE=0
ASSUME_YES=0
FORCE=0

die() { printf '\\n✗ %s\\n' "$*" >&2; exit 1; }
say() { printf '%s\\n' "$*"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run)      DRY_RUN=1 ;;
    --allow-delete) ALLOW_DELETE=1 ;;
    --yes|-y)       ASSUME_YES=1 ;;
    --force)        FORCE=1 ;;
    -h|--help)      sed -n '2,12p' "$0"; exit 0 ;;
    *)              target="$1" ;;
  esac
  shift
done

# Nothing to apply: do not even look for an engine, and do not ask about
# installing one — there is nothing to replay.
if [ "$CHANGES" -eq 0 ]; then
  say "Nothing to change in \\"$ARCHIVE_NAME\\"."
  exit 0
fi

# ── 0. pick the engine that edits the archive ─────────────────────────────
SEVENZIP=''
for candidate in 7z 7zz 7za 7zr; do
  if command -v "$candidate" >/dev/null 2>&1; then SEVENZIP="$candidate"; break; fi
done

install_7zip() {
  # The command is always shown before it runs, and printed again if it fails,
  # so the user can install 7-Zip themselves and re-run this script.
  local manager=''
  local cmd=''
  if [ "$(uname -s)" = "Darwin" ]; then
    if command -v brew >/dev/null 2>&1; then
      manager=brew
      cmd='brew install p7zip'
    else
      say 'Install 7-Zip yourself with: brew install p7zip'
      return 1
    fi
  elif command -v apt-get >/dev/null 2>&1; then
    manager=apt
    cmd='sudo apt-get install -y p7zip-full'
  elif command -v dnf >/dev/null 2>&1; then
    manager=dnf
    cmd='sudo dnf install -y p7zip'
  elif command -v pacman >/dev/null 2>&1; then
    manager=pacman
    cmd='sudo pacman -S --noconfirm p7zip'
  elif command -v apk >/dev/null 2>&1; then
    manager=apk
    cmd='sudo apk add p7zip'
  else
    say 'Install 7-Zip with your package manager (p7zip-full on Debian/Ubuntu, p7zip on Fedora/Arch), then run this script again.'
    return 1
  fi
  say "Running: $cmd"
  case "$manager" in
    brew) brew install p7zip ;;
    apt) sudo apt-get install -y p7zip-full ;;
    dnf) sudo dnf install -y p7zip ;;
    pacman) sudo pacman -S --noconfirm p7zip ;;
    apk) sudo apk add p7zip ;;
  esac
  local status=$?
  if [ "$status" = 0 ]; then
    return 0
  fi
  say "That did not work. Install 7-Zip yourself with: $cmd"
  return 1
}

if [ -z "$SEVENZIP" ]; then
  # Offer the install, but only to someone who is there to answer — and only
  # when they can see the command that is about to run.
  if [ "$ASSUME_YES" = 0 ] && [ -t 0 ]; then
    printf '\\n7-Zip is not installed. Install it now? [y/N]: '
    read -r reply || reply=''
    case "$reply" in
      y|Y|yes)
        if install_7zip; then
          for candidate in 7z 7zz 7za 7zr; do
            if command -v "$candidate" >/dev/null 2>&1; then SEVENZIP="$candidate"; break; fi
          done
        fi
        ;;
    esac
  fi
fi

PYTHON=''
if command -v python3 >/dev/null 2>&1; then PYTHON=python3; fi

if [ -n "$SEVENZIP" ]; then
  ENGINE=7z
elif [ -n "$PYTHON" ]; then
  ENGINE=python
  say "7-Zip is not installed — using Python 3 instead."
else
  die "nothing here can edit an archive: install 7-Zip (apt install p7zip-full, brew install p7zip) or Python 3, and run this script again."
fi

# ── 1. the archive must be the one that was imported ───────────────────────
if [ -f "$target" ]; then
  ARCHIVE="$(cd "$(dirname -- "$target")" && pwd)/$(basename -- "$target")"
else
  ARCHIVE="$(cd "$target" && pwd)/$ARCHIVE_NAME"
fi
[ -f "$ARCHIVE" ] || die "cannot find '$ARCHIVE_NAME' in '$target' — point the script at the archive (or pass its path)"

case "$ARCHIVE" in
  *.rar|*.RAR)
    die "RAR archives can be read but not rewritten by 7-Zip — this archive is left untouched." ;;
  *.part*.rar|*.z01|*.7z.001)
    die "multi-volume archives are not supported — this archive is left untouched." ;;
  *.exe)
    die "self-extracting archives are not supported — this archive is left untouched." ;;
esac

WORK="$(mktemp -d)"
cleanup() {
  if [ -n "$WORK" ]; then rm -rf "$WORK"; fi
}
trap cleanup EXIT

if [ "$ENGINE" = "python" ]; then
  cat > "$WORK/fewer_zip.py" <<'FEWER_ZIP_PY_EOF'
__PYTHON__
FEWER_ZIP_PY_EOF
  if [ "$FORCE" = 0 ]; then
    "$PYTHON" "$WORK/fewer_zip.py" --list "$ARCHIVE" >/dev/null 2>&1 ||
      die "cannot read '$ARCHIVE' — it may be password-protected or damaged; it is left untouched."
  fi
elif [ "$FORCE" = 0 ]; then
  "$SEVENZIP" l -bso0 -bsp0 "$ARCHIVE" >/dev/null 2>&1 ||
    die "cannot read '$ARCHIVE' — it may be password-protected or damaged; it is left untouched."
fi

# ── 2. what should we do? ─────────────────────────────────────────────────
if [ "$ASSUME_YES" = 0 ] && [ -t 0 ]; then
  say ""
  say "fewer — $CHANGES change(s) inside \\"$ARCHIVE_NAME\\""
  printf 'Apply them? [y]es / [d]ry-run / [n]o (default: n): '
  read -r reply || reply=''
  case "\${reply:-n}" in
    y|Y|yes) ;;
    d|D|dry) DRY_RUN=1 ;;
    *) say "Nothing changed."; exit 0 ;;
  esac
  if [ "$DELETES" -gt 0 ] && [ "$ALLOW_DELETE" = 0 ]; then
    printf 'Also delete %s entry(ies) from the archive? This cannot be undone. [y/N]: ' "$DELETES"
    read -r reply || reply=''
    case "$reply" in y|Y|yes) ALLOW_DELETE=1 ;; esac
  fi
elif [ "$DELETES" -gt 0 ] && [ "$ALLOW_DELETE" = 0 ]; then
  say "note: no terminal to confirm — $DELETES deletion(s) will be skipped"
fi

`;
export const BASH_ARCHIVE_CHECKS = `# ── 3. the plan ──────────────────────────────────────────────────────────
__PLAN__

archive_entries() {
  # Every path inside the archive, one per line.
  if [ "$ENGINE" = "7z" ]; then
    "$SEVENZIP" l -slt "$ARCHIVE" 2>/dev/null | sed -n 's/^Path = //p' | tail -n +2
  else
    "$PYTHON" "$WORK/fewer_zip.py" --list "$ARCHIVE" 2>/dev/null
  fi
}

has_entry() {
  archive_entries | grep -Fxq -- "$1"
}

# A destination that is another move's source is fine: that entry is moved
# aside first, so the path is free by the time it is written.
is_move_source() {
  local j=0
  while [ "$j" -lt "$N_MOVES" ]; do
    [ "\${STAGE_FROM[$j]}" = "$1" ] && return 0
    j=$((j+1))
  done
  return 1
}

is_delete_path() {
  local j=0
  while [ "$j" -lt "$N_DELETES" ]; do
    [ "\${DELETE_PATHS[$j]}" = "$1" ] && return 0
    j=$((j+1))
  done
  # A pre-delete goes first and frees the path before the rename lands.
  j=0
  while [ "$j" -lt "$N_PRE_DELETES" ]; do
    [ "\${PRE_DELETES[$j]}" = "$1" ] && return 0
    j=$((j+1))
  done
  return 1
}

# ── 4. checks (nothing has been touched yet) ──────────────────────────────
if [ "$FORCE" = 0 ]; then
  listing="$(archive_entries)"
  j=0
  while [ "$j" -lt "$N_MOVES" ]; do
    from="\${STAGE_FROM[$j]}"
    printf '%s\\n' "$listing" | grep -Fxq -- "$from" ||
      die "the archive has no entry '$from' — is this the archive you edited? (--force to override)"
    j=$((j+1))
  done
  j=0
  while [ "$j" -lt "$N_MOVES" ]; do
    to="\${COMMIT_TO[$j]}"
    if printf '%s\\n' "$listing" | grep -Fxq -- "$to" &&
       ! is_move_source "$to" && ! is_delete_path "$to"; then
      die "'$to' is already in the archive — resolve it by hand (--force to override)"
    fi
    j=$((j+1))
  done
  present=0
  i=0
  while [ "$i" -lt "$N_FINGERPRINT" ]; do
    printf '%s\\n' "$listing" | grep -Fxq -- "\${FINGERPRINT[$i]}" && present=$((present+1))
    i=$((i+1))
  done
  if [ "$present" -lt "$FINGERPRINT_MIN" ]; then
    die "only $present of $N_FINGERPRINT sampled entries are in the archive — wrong archive? (--force to override)"
  fi
fi

`;

export const BASH_ARCHIVE_APPLY = `# ── 5. apply ───────────────────────────────────────────────────────────

# ── 5a. the Python engine: one rebuild of the archive ─────────────────────
# The plan becomes a name mapping, so a swap is free and a failure leaves the
# original archive untouched.
if [ "$ENGINE" = "python" ]; then
  plan="$WORK/plan.tsv"
  : > "$plan"
  # Deletions first: the filter below drops the moves that needed them.
  j=0
  while [ "$j" -lt "$N_PRE_DELETES" ]; do
    printf 'PREDELETE\\t%s\\n' "\${PRE_DELETES[$j]}" >> "$plan"
    j=$((j+1))
  done
  j=0
  while [ "$j" -lt "$N_DELETES" ]; do
    printf 'DELETE\\t%s\\n' "\${DELETE_PATHS[$j]}" >> "$plan"
    j=$((j+1))
  done
  j=0
  while [ "$j" -lt "$N_MOVES" ]; do
    printf 'MOVE\\t%s\\t%s\\n' "\${STAGE_FROM[$j]}" "\${MOVE_TO[$j]}" >> "$plan"
    j=$((j+1))
  done
  j=0
  while [ "$j" -lt "$N_ADD_DIRS" ]; do
    printf 'ADDDIR\\t%s\\n' "\${ADD_DIRS[$j]}" >> "$plan"
    j=$((j+1))
  done
  j=0
  while [ "$j" -lt "$N_ADD_FILES" ]; do
    printf 'ADDFILE\\t%s\\n' "\${ADD_FILES[$j]}" >> "$plan"
    j=$((j+1))
  done
  j=0
  while [ "$j" -lt "$N_ADD_COPIES" ]; do
    printf 'ADDCOPY\\t%s\\t%s\\n' "\${ADD_COPIES[$j]}" "\${ADD_COPIES[$((j+1))]}" >> "$plan"
    j=$((j+2))
  done
  if [ "$DRY_RUN" = 1 ]; then
    j=0
    while [ "$j" -lt "$N_PRE_DELETES" ]; do
      printf '+ delete %q (frees the renamed-into path) (dry run)\n' "\${PRE_DELETES[$j]}"
      j=$((j+1))
    done
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      printf '+ rename %q → %q\\n' "\${STAGE_FROM[$j]}" "\${MOVE_TO[$j]}"
      j=$((j+1))
    done
    j=0
    while [ "$j" -lt "$N_DELETES" ]; do
      printf '+ delete %q\\n' "\${DELETE_PATHS[$j]}"
      j=$((j+1))
    done
    j=0
    while [ "$j" -lt "$N_ADDS" ]; do
      printf '+ add %q\\n' "\${ADDS[$j]}"
      j=$((j+1))
    done
  else
    if [ "$ALLOW_DELETE" = 0 ] && [ "$((N_DELETES + N_PRE_DELETES))" -gt 0 ]; then
      # Deletions are not allowed: drop them, and the moves that needed the
      # freed path (they would land on an entry that is still there).
      awk -F'\\t' '$1 == "DELETE" || $1 == "PREDELETE" { drop[$2] = 1; next } $1 == "MOVE" && ($3 in drop) { next } { print }' \\
        "$plan" > "$plan.kept"
      mv "$plan.kept" "$plan"
    fi
    "$PYTHON" "$WORK/fewer_zip.py" --apply "$ARCHIVE" "$plan" ||
      die "Python could not rewrite the archive — it is unchanged"
  fi
  say ""
  say "Done — $CHANGES change(s) applied to $ARCHIVE."
  exit 0
fi

# ── 5b. the 7-Zip engine ─────────────────────────────────────────────────
staging=''
done_ok=0
cleanup() {
  if [ "$done_ok" = 1 ]; then
    if [ -n "$staging" ]; then rm -rf "$staging"; fi
  else
    if [ -n "$staging" ]; then printf '\\n✗ stopped — staged files are still in %s\\n' "$staging" >&2; fi
  fi
  if [ -n "$WORK" ]; then rm -rf "$WORK"; fi
}
trap cleanup EXIT

# A deletion that frees the path another entry moves into has to happen first.
if [ "$DRY_RUN" = 1 ]; then
  i=0
  while [ "$i" -lt "$N_PRE_DELETES" ]; do
    printf '+ 7z d %s %q (frees the renamed-into path) (dry run)\n' "$ARCHIVE" "\${PRE_DELETES[$i]}"
    i=$((i+1))
  done
else
i=0
while [ "$i" -lt "$N_PRE_DELETES" ]; do
  p="\${PRE_DELETES[$i]}"
  say "· delete $p"
  "$SEVENZIP" d -bso0 -bsp0 "$ARCHIVE" "$p" ||
    die "7-Zip could not delete '$p'"
  i=$((i+1))
done
fi

if [ "$N_MOVES" -gt 0 ]; then
  if [ "$DRY_RUN" = 1 ]; then
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      printf '+ 7z rn %s %q %q\\n' "$ARCHIVE" "\${STAGE_FROM[$j]}" "\${COMMIT_TO[$j]}"
      j=$((j+1))
    done
  else
    # Phase 1: every source is renamed aside to a temporary name. 7-Zip
    # renames one pair per call and carries a folder's subtree with it, so the
    # deepest source goes first and each rename gets its own call.
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      from="\${STAGE_FROM[$j]}"
      say "· move aside $from"
      "$SEVENZIP" rn -bso0 -bsp0 "$ARCHIVE" "$from" ".fewer-tmp-$j" ||
        die "7-Zip could not set '$from' aside — the archive is unchanged"
      j=$((j+1))
    done
    # Phase 2: each temporary name goes to its real destination, parents
    # first, so a destination inside another moved folder finds it in place.
    j=0
    while [ "$j" -lt "$N_MOVES" ]; do
      to="\${COMMIT_TO[$j]}"
      tmp=".fewer-tmp-\${COMMIT_IDX[$j]}"
      say "· move to $to"
      "$SEVENZIP" rn -bso0 -bsp0 "$ARCHIVE" "$tmp" "$to" ||
        die "7-Zip could not place '$to' — the archive holds the entries as '.fewer-tmp-N'"
      j=$((j+1))
    done
  fi
fi

if [ "$N_DELETES" -gt 0 ]; then
  if [ "$ALLOW_DELETE" = 1 ]; then
    say "· delete $N_DELETES entr(y|ies)"
    "$SEVENZIP" d -bso0 -bsp0 "$ARCHIVE" "\${DELETE_PATHS[@]}" ||
      die "7-Zip could not delete the entries — the archive is unchanged"
  else
    i=0
    while [ "$i" -lt "$N_DELETES" ]; do
      printf '· skipped delete %q (not allowed)\\n' "\${DELETE_PATHS[$i]}"
      i=$((i+1))
    done
  fi
fi

if [ "$N_ADDS" -gt 0 ]; then
  if [ "$DRY_RUN" = 1 ]; then
    i=0
    while [ "$i" -lt "$N_ADDS" ]; do
      printf '+ 7z a %s %q\\n' "$ARCHIVE" "\${ADDS[$i]}"
      i=$((i+1))
    done
  else
    # New entries are staged in a temp folder that mirrors their paths inside
    # the archive, then added from there.
    staging="$(mktemp -d)"
    i=0
    while [ "$i" -lt "$N_ADD_DIRS" ]; do
      rel="\${ADD_DIRS[$i]}"
      mkdir -p -- "$staging/$rel"
      i=$((i+1))
    done
    i=0
    while [ "$i" -lt "$N_ADD_FILES" ]; do
      rel="\${ADD_FILES[$i]}"
      mkdir -p -- "$staging/$(dirname -- "$rel")"
      : > "$staging/$rel"
      i=$((i+1))
    done
    i=0
    while [ "$i" -lt "$((N_ADD_COPIES * 2))" ]; do
      src="\${ADD_COPIES[$i]}"; rel="\${ADD_COPIES[$((i+1))]}"
      # A duplicate is taken out of the archive first, so it keeps its bytes.
      # 7z x keeps the path, so the extracted tree mirrors the source path.
      rm -rf -- "$staging/copy"
      mkdir -p -- "$staging/copy"
      "$SEVENZIP" x -bso0 -bsp0 -o"$staging/copy" "$ARCHIVE" "$src" ||
        die "could not read '$src' out of the archive"
      mkdir -p -- "$staging/$(dirname -- "$rel")"
      mv -- "$staging/copy/$src" "$staging/$rel" ||
        die "could not stage the copy of '$src'"
      i=$((i+2))
    done
    i=0
    while [ "$i" -lt "$N_ADDS" ]; do
      rel="\${ADDS[$i]}"
      say "· add $rel"
      ( cd "$staging" && "$SEVENZIP" a -bso0 -bsp0 "$ARCHIVE" "$rel" ) ||
        die "7-Zip could not add '$rel'"
      i=$((i+1))
    done
  fi
fi

done_ok=1
say ""
say "Done — $CHANGES change(s) applied to $ARCHIVE."
`;
